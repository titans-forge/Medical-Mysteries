test('legacy active records continue exactly like the frozen original engine and save only an original-build sidecar', async () => {
  for (const value of fixture.expected.filter((item) => item.status.startsWith('active'))) {
    let time = fixture.clock + 100;
    const store = memory(fixture.storage);
    const oldStore = memory(fixture.storage);
    const client = api(store, () => time);
    const oldClient = createOriginalAPI(originalBundle, { storage: oldStore, clock: () => time });
    let stage = await success(client, `/api/resume?session_id=${value.id}`);
    const expectedStage = await success(oldClient, `/api/resume?session_id=${value.id}`);
    sameOriginal(stage, expectedStage);
    const spec = originalBundle.cases.find((item) => item.case_id === value.case_id);
    while (!stage.finished) {
      const originalStage = spec.stages.find((item) => item.view.stage_id === stage.stage_id);
      const body = { session_id: value.id, option_id: originalStage.choices.find((choice) => choice.result.correct).id, confidence: 40 };
      time += 11;
      const actual = await success(client, '/api/answer', body);
      const expected = await success(oldClient, '/api/answer', body);
      sameOriginal(actual, expected);
      assert.equal(actual.content_version, 1);
      if (actual.finished) break;
      stage = actual.next;
    }
    assert.equal(store.getItem(LEGACY_KEY), oldText);
    const envelope = JSON.parse(store.getItem(`${PREFIX}${value.id}`));
    assert.equal(envelope.build_id, originalBundle.build_id);
    assert.equal(envelope.content_version, 1);
    const cold = await success(api(store, () => time), `/api/resume?session_id=${value.id}`);
    const expected = await success(oldClient, `/api/resume?session_id=${value.id}`);
    sameOriginal(cold, expected);
  }
});

