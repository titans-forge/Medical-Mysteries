function memory(initial = {}) {
  const values = new Map(Object.entries(initial));
  return { values, get length() { return values.size; }, key: (index) => [...values.keys()][index] ?? null,
    getItem: (key) => values.get(key) ?? null, setItem: (key, value) => { values.set(key, String(value)); }, removeItem: (key) => values.delete(key) };
}
function api(storage, clock = () => fixture.clock + 100) {
  return createOfflineAPI(currentBundle, { legacyBundles: [originalBundle], storage, clock });
}
async function request(client, path, body) {
  const response = await client(path, body === undefined ? {} : { method: 'POST', body: JSON.stringify(body) });
  return { ok: response.ok, status: response.status, data: await response.json() };
}
async function success(client, path, body) {
  const response = await request(client, path, body);
  assert.equal(response.ok, true, response.data.error);
  return response.data;
}
async function failure(client, path, body) {
  const response = await request(client, path, body);
  assert.equal(response.ok, false);
  assert.equal(response.status, 400);
  return response.data;
}
function projectOriginal(actual, expected) {
  if (Array.isArray(expected)) {
    assert.ok(Array.isArray(actual));
    assert.equal(actual.length, expected.length);
    return expected.map((value, index) => projectOriginal(actual[index], value));
  }
  if (expected && typeof expected === 'object') {
    assert.ok(actual && typeof actual === 'object');
    return Object.fromEntries(Object.keys(expected).map((key) => [key, projectOriginal(actual[key], expected[key])]));
  }
  return actual;
}
function sameOriginal(actual, expected) { assert.deepEqual(projectOriginal(actual, expected), expected); }
function oldEnvelope(record) {
  return JSON.stringify({ schema: 2, build_id: originalBundle.build_id, content_version: 1,
    edition_label: 'Original story edition', record });
}
async function start(client, spec = currentBundle.cases[0], build_id) {
  return success(client, '/api/start', { tier: spec.tier, case_id: spec.case_id, ...(build_id === undefined ? {} : { build_id }) });
}
async function complete(client, started, bundle = currentBundle) {
  let result = started;
  const spec = bundle.cases.find((item) => item.case_id === started.case_id);
  while (!result.finished) {
    const stage = spec.stages.find((item) => item.view.stage_id === result.stage_id);
    assert.ok(stage);
    result = await success(client, '/api/answer', { session_id: started.session_id,
      option_id: stage.choices.find((choice) => choice.result.correct).id, confidence: 60 });
    if (!result.finished) result = { ...result.next, session_id: started.session_id };
  }
  return result;
}

