test('an unreadable legacy source suppresses sidecar persistence even when v2 keys remain writable', async () => {
  let time = fixture.clock + 100;
  const store = memory(fixture.storage);
  const client = api(store, () => time);
  const oldClient = createOriginalAPI(originalBundle, { storage: store, clock: () => time });
  const value = fixture.expected.find((item) => item.status.startsWith('active'));
  const restored = await success(client, `/api/resume?session_id=${value.id}`);
  const spec = originalBundle.cases.find((item) => item.case_id === value.case_id);
  const stage = spec.stages.find((item) => item.view.stage_id === restored.stage_id);
  time += 10;
  await success(oldClient, '/api/answer', { session_id: value.id,
    option_id: stage.choices.find((choice) => choice.result.correct).id });
  const newerOriginal = store.getItem(LEGACY_KEY);
  const get = store.getItem;
  store.getItem = (key) => { if (key === LEGACY_KEY) throw new Error('source blocked'); return get(key); };
  const result = await success(client, '/api/answer', { session_id: value.id,
    option_id: stage.choices.find((choice) => !choice.result.correct).id });
  assert.equal(result.persistence_status, 'unavailable');
  assert.match(result.persistence_note, /only in this tab/);
  assert.equal(store.getItem(`${PREFIX}${value.id}`), null);
  assert.equal(store.values.get(LEGACY_KEY), newerOriginal);
  store.getItem = get;
  const cold = await success(api(store, () => time), `/api/resume?session_id=${value.id}`);
  assert.equal(cold.stage_number, restored.stage_number + 1);
});

