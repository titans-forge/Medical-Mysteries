test('one recorded event time keeps live and replayed timer-boundary results identical', async () => {
  let wallTime = 100;
  const clock = () => wallTime++;
  const store = memory();
  const client = api(store, clock);
  const spec = originalBundle.cases.find((item) => item.case_id === 'stu-001-mountain-acid');
  const started = await start(client, spec, originalBundle.build_id);
  assert.equal(started.pressure_deadline, 160);
  wallTime = 160;
  const wrong = await success(client, '/api/answer', { session_id: started.session_id, option_id: 'b', confidence: 80 });
  assert.equal(wrong.time_expired, false, 'the recorded event is exactly at the inclusive deadline');
  assert.equal(wallTime, 161, 'a mutation reads the live clock exactly once');
  const resumed = await success(api(store, () => 1000), `/api/resume?session_id=${started.session_id}`);
  assert.equal(resumed.last_result.time_expired, wrong.time_expired);
  const envelope = JSON.parse(store.getItem(`${PREFIX}${started.session_id}`));
  assert.equal(envelope.record.actions[0].time, 160);
  wallTime = 170;
  let result = await success(client, '/api/answer', { session_id: started.session_id, option_id: 'a', confidence: null });
  while (!result.finished) {
    const stage = spec.stages.find((item) => item.view.stage_id === result.next.stage_id);
    wallTime += 5;
    result = await success(client, '/api/answer', { session_id: started.session_id,
      option_id: stage.choices.find((choice) => choice.result.correct).id });
  }
  const completed = await success(api(store, () => 2000), `/api/resume?session_id=${started.session_id}`);
  assert.deepEqual(completed.last_result, result);
});

